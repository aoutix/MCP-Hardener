import { stringify } from "yaml";
import type { Effect, Posture } from "@hmcp/core";
import type { AdoptionPlan } from "./adopt-plan.js";

/**
 * Rendering the two files adoption writes.
 *
 * Pure, and deliberately not a `yaml.stringify` of one big object: the
 * comments are half the product. Someone reading `policy.yaml` in a diff a
 * month from now needs to know why `rules` is empty and why `egress.methods`
 * names POST, and neither is recoverable from the values alone.
 *
 * Each section is stringified on its own and concatenated. Hand-writing the
 * YAML would be shorter and would also mean hand-escaping tool names, commands
 * and URLs that came from somewhere else.
 */

export interface ProbedTool {
  readonly localName: string;
  readonly upstream: string;
  readonly effect: Effect | null;
  readonly effectSource: string;
  readonly hidden: boolean;
  readonly injection: { readonly patternIds: readonly string[]; readonly action: string } | null;
}

export interface EmitOptions {
  readonly name: string;
  readonly posture: Posture;
  /** Tools the probe could not classify, which policy will refuse. */
  readonly unclassified?: readonly ProbedTool[] | undefined;
  /** How many tools the gateway would expose, for the tool_budget note. */
  readonly toolCount?: number | undefined;
}

function yamlBlock(value: Record<string, unknown>): string {
  return stringify(value, { lineWidth: 0 });
}

/** Drops the keys `UpstreamSchema`'s defaults filled in with nothing. */
function pruneUpstream(upstream: Record<string, unknown>): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(upstream)) {
    if (Array.isArray(value) && value.length === 0) continue;
    if (value !== null && typeof value === "object" && Object.keys(value).length === 0) continue;
    out[key] = value;
  }
  return out;
}

export function emitGatewayYaml(plan: AdoptionPlan, options: EmitOptions): string {
  const out: string[] = [];

  out.push("# Generated by `hmcp-gateway adopt`. Safe to edit, and safe to commit: every");
  out.push("# secret stays in the client config that already held it, and is forwarded");
  out.push("# into the upstream by name through pass_env.");
  if (plan.secretsOnDisk) {
    out.push("#");
    out.push("# EXCEPT: --copy-env was used, so a literal credential IS present below.");
    out.push("# Do not commit this file.");
  }

  if (plan.skipped.length > 0) {
    out.push("#");
    out.push("# Servers that were NOT adopted, and are still configured directly in the");
    out.push("# client (recorded here so the reason outlives the terminal):");
    for (const skip of plan.skipped) {
      out.push(`#   ${skip.name}: ${skip.reason}`);
      out.push(`#     -> ${skip.remedy}`);
    }
  }
  out.push("");

  out.push(yamlBlock({ version: 1, name: options.name }).trimEnd());
  out.push("");
  out.push("# Relative to this file's own directory.");
  out.push(yamlBlock({ policy: "./policy.yaml" }).trimEnd());
  out.push("");

  out.push("# Each stdio upstream inherits nothing from this process except the names it");
  out.push("# lists in pass_env, so one upstream's credential is not handed to the rest.");
  out.push(
    yamlBlock({
      upstreams: plan.upstreams.map((u) => pruneUpstream(u.upstream as unknown as Record<string, unknown>))
    }).trimEnd()
  );
  out.push("");

  out.push("# What to do with an upstream tool whose description carries injected");
  out.push("# instructions. `strip` replaces the text and keeps the tool usable; `deny`");
  out.push("# hides it; `annotate` labels the text as untrusted and leaves it.");
  out.push(yamlBlock({ on_injection: "strip" }).trimEnd());
  out.push("");
  out.push("# Prefix every tool with `<server>__`, so two upstreams cannot collide and the");
  out.push("# audit log always says which server a call went to.");
  out.push(yamlBlock({ namespace: true }).trimEnd());

  return `${out.join("\n")}\n`;
}

export function emitPolicyYaml(plan: AdoptionPlan, options: EmitOptions): string {
  const out: string[] = [];
  const http = plan.upstreams.filter((u) => u.upstream.transport === "http");

  out.push("# Generated by `hmcp-gateway adopt`. This file is the whole of what the");
  out.push("# gateway will and will not let through, so it is the one worth reviewing.");
  out.push("");

  out.push(yamlBlock({ version: 1, name: `${options.name}-adopted` }).trimEnd());
  out.push("");

  out.push("# `mode` decides every call no rule matches. Under approve-writes a read goes");
  out.push("# straight through and anything that mutates is held for a human. Under");
  out.push("# read-only a write is refused outright; under locked, so is a read.");
  out.push("#");
  out.push("# `on_unclassified: deny` is what makes a tool an upstream adds tomorrow");
  out.push("# unreachable today. It is the point of the gateway -- see the stubs at the");
  out.push("# bottom of this file for how to classify one deliberately.");
  out.push(yamlBlock({ defaults: { mode: options.posture, on_unclassified: "deny" } }).trimEnd());
  out.push("");

  out.push("# Deliberately empty.");
  out.push("#");
  out.push("# A rule is only needed to say something the posture above does not already");
  out.push("# say. The gateway classifies each tool from its MCP annotations and its name,");
  out.push("# handling snake_case, kebab-case and camelCase alike, and `decide()` falls");
  out.push("# back to the posture for anything no rule matches.");
  out.push("#");
  out.push("# Beware of reaching for a glob like `*__{get,list,read}_*` here: it matches");
  out.push("# only one naming convention, so it silently misses `getIssue` and");
  out.push("# `list-issues`, and where it does match it overrides both the posture and the");
  out.push("# gateway's own classification -- including its refusal to believe a server");
  out.push("# that marks its own delete tool read-only.");
  out.push(yamlBlock({ rules: [] }).trimEnd());
  out.push("");

  if (http.length > 0) {
    out.push("# Applies to HTTP upstreams only. A stdio upstream is a child process, and");
    out.push("# what it may reach is governed by gateway.yaml instead.");
    out.push("#");
    out.push("# `methods` must include POST: opening an MCP session over Streamable HTTP");
    out.push("# is a POST, and it is checked against this list before the connection is");
    out.push("# made. The schema default is [GET, HEAD], which refuses every upstream.");
    const egress: Record<string, unknown> = {
      allow: plan.egressAllow,
      methods: ["GET", "POST"]
    };
    if (plan.egressNeedsLocalHttp) {
      out.push("#");
      out.push("# WARNING: an adopted upstream listens on loopback or a private address, so");
      out.push("# the SSRF protections below are off -- for EVERY HTTP upstream of this");
      out.push("# gateway, not just that one. The upstreams that forced it:");
      for (const u of http) {
        if (u.warnings.some((w) => w.includes("SSRF"))) {
          out.push(`#   ${u.upstream.name} (${u.originalName})`);
        }
      }
      out.push("# Removing that upstream and setting these back to true is the safer end");
      out.push("# state if it was adopted by accident.");
      egress["block_private_ips"] = false;
      egress["allow_ip_literals"] = true;
      egress["allow_http"] = true;
    }
    out.push(yamlBlock({ egress }).trimEnd());
    out.push("");
  }

  out.push("# `both` tries the client first and parks the request if it cannot ask.");
  out.push("#");
  out.push("# Worth leaving alone: the gateway offers an in-client prompt only when the");
  out.push("# client advertises the elicitation capability. With `elicit` and a client");
  out.push("# that does not, a held write waits with no way to approve it. With `both`,");
  out.push("# the same write is waiting for `hmcp pending` and `hmcp approve <id>`, or for");
  out.push("# the console.");
  out.push(yamlBlock({ approvals: { mode: "both", ttl_seconds: 300, single_use: true } }).trimEnd());
  out.push("");

  out.push("# Every decision, allowed or refused, with each record chained to the last so");
  out.push("# an edit to the middle of the log does not verify. `hmcp audit verify`.");
  out.push(yamlBlock({ audit: { enabled: true, path: "~/.hmcp/audit.jsonl", hash_chain: true } }).trimEnd());

  if (options.toolCount !== undefined) {
    out.push("");
    out.push(`# This gateway currently exposes ${options.toolCount} tool(s). The default ceiling is 40;`);
    out.push("# above it the scanner reports that the tool set is hard to review, which is");
    out.push("# a real cost of wrapping several servers at once. Raise it deliberately, or");
    out.push("# switch off what the agent does not need (`hmcp-gateway exposure off`).");
    out.push(`# tool_budget: ${Math.max(40, options.toolCount)}`);
  }

  const unclassified = options.unclassified ?? [];
  if (unclassified.length > 0) {
    out.push("");
    out.push(`# ${unclassified.length} tool(s) could not be classified, and are refused by`);
    out.push("# `on_unclassified: deny` above. Uncomment a stub to classify one.");
    out.push("#");
    out.push("# `effect:` is the part that matters and the part that is easy to leave out.");
    out.push("# An unclassified tool is refused BEFORE rules are consulted, so a rule");
    out.push("# carrying only `decision: allow` changes nothing at all -- it is the");
    out.push("# `effect:` that gives the tool a classification for the decision to act on.");
    out.push("#");
    out.push("# Add these to `rules` above, not here.");
    for (const tool of unclassified) {
      out.push("#");
      out.push(`#   - id: classify-${tool.localName}`);
      out.push(`#     match: ${JSON.stringify(tool.localName)}`);
      out.push("#     effect: read        # or write, or destructive");
      out.push("#     decision: allow     # or approve, or deny");
    }
  }

  return `${out.join("\n")}\n`;
}

/** The entry that replaces the adopted servers in the client's own config. */
export function emitClientEntry(
  plan: AdoptionPlan,
  options: { readonly configPath: string; readonly command: string; readonly args: readonly string[] }
): Record<string, unknown> {
  const entry: Record<string, unknown> = {
    command: options.command,
    args: [...options.args, "serve", "-c", options.configPath]
  };
  if (Object.keys(plan.gatewayEnv).length > 0) {
    entry["env"] = { ...plan.gatewayEnv };
  }
  return entry;
}
